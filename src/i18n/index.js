// Kuhanin ang salin para sa isang key sa isang lang, may param na palit.
export function translate(lang, key, params) {
  const table = messages[lang] || messages.tl;
  let str = table[key] != null ? table[key] : messages.tl[key] != null ? messages.tl[key] : key;
  if (params) {
    Object.keys(params).forEach((p) => {
      str = str.replace(new RegExp(`\\{${p}\\}`, "g"), params[p]);
    });
  }
  return str;
}
